def tab_frontier(res, out):
    """The gate / weight-interpolation frontier (answers 'is learning itself the problem?')."""
    gates = sorted([k for k in res if k.startswith('B3_gate')], key=lambda x: float(x[7:]))
    winterp = sorted([k for k in res if k.startswith('B4_winterp')], key=lambda x: float(x[10:]))
    L = ['% AUTO-GENERATED by scripts/finalize_ext_tables.py from metrics_align.json',
         '\\centering\\small',
         '\\caption{\\textbf{The novel-class frontier: interpolating between the frozen prediction and the '
         'seen-only head.} ADE20K-150 dense-CLIP, five splits. $g$ mixes the two \\emph{probability} '
         'distributions (B3); $\\eta$ scales the learned \\emph{logit residual} (B4). Both recover the '
         'frozen baseline at $0$ and the collapsed head at $1$, so the column shows the price of every '
         'intermediate operating point. $C$ is novel-IoU relative to the frozen baseline.}',
         '\\label{tab:r2_frontier}',
         '\\scriptsize\\setlength{\\tabcolsep}{2.6pt}',
         '\\begin{tabular}{@{}lcccccc@{}}',
         '\\toprule',
         'Setting & mIoU & seen-IoU & novel-IoU & hIoU & ECE$\\downarrow$ & $C$ \\\\',
         '\\midrule']
    if 'uncal' in res:
        L.append(row(res, 'uncal', 'frozen baseline', keys=('mIoU', 'seenIoU', 'novelIoU', 'hIoU', 'ECE'),
                     extra=()))
    L.append('\\midrule')
    for k in gates:
        L.append(row(res, k, f'B3 output gate $g{{=}}{k[7:]}$',
                     keys=('mIoU', 'seenIoU', 'novelIoU', 'hIoU', 'ECE'), extra=()))
    L.append('\\midrule')
    for k in winterp:
        L.append(row(res, k, f'B4 residual scale $\\eta{{=}}{k[10:]}$',
                     keys=('mIoU', 'seenIoU', 'novelIoU', 'hIoU', 'ECE'), extra=()))
    L += ['\\bottomrule', '\\end{tabular}']
    write(out, L)


def tab_diag(res, out):
    """Confound ablation (answers C6)."""
    L = ['% AUTO-GENERATED by scripts/finalize_ext_tables.py from metrics_diag.json',
         '\\centering\\small',
         '\\caption{\\textbf{Confound ablation: only bounding the alignment drift prevents the collapse.} '
         'ADE20K-150 dense-CLIP, five splits; each row changes exactly one factor of the seen-only head. '
         'Class balancing, the training objective, a learned logit scale and restricting training to '
         'spatially pure patches all leave novel-IoU at $\\le0.3$, as does supervision breadth at $60$ '
         'classes and above. The one partial exception is the narrowest supervision setting, $30$ seen '
         'classes, which reaches novel-IoU $3.3$ -- with a standard deviation of $4.3$, so it is not '
         'stable across splits, and still a collapse to CI $0.22$ against the $15.1$ frozen baseline. '
         'Only the trust region rescues novel classes, and it does so monotonically in the bound '
         '($\\tau{=}0.5$ recovers novel-IoU $14.6$ at drift $5.6$), matching the distillation frontier '
         'of Table~\\ref{tab:r2_frontier}. $C$ is the collapse index (novel-IoU relative to the '
         'frozen baseline).}',
         '\\label{tab:r2_diag}',
         '\\setlength{\\tabcolsep}{7pt}',
         '\\begin{tabular}{@{}lccccccc@{}}',
         '\\toprule',
         'Condition & mIoU & seen-IoU & novel-IoU & hIoU & ECE$\\downarrow$ & drift & $C$ \\\\',
         '\\midrule']
    order = (['uncal', 'head_ce', 'C1_class_balanced', 'C2_focal', 'C2_cosmargin', 'C3_learned_scale']
             + sorted([k for k in res if k.startswith('C4_')], key=lambda x: float(x[6:]))
             + sorted([k for k in res if k.startswith('C5_')], key=lambda x: int(x[8:]))
             + ['C6_pure_only'])
    for k in order:
        if k not in res:
            continue
        lab = PRETTY.get(k)
        if lab is None and k.startswith('C4_'):
            lab = f'C4 trust region $\\tau{{=}}{k[6:]}$'
        if lab is None and k.startswith('C5_'):
            lab = f'C5 supervision breadth: {k[8:]} seen classes'
        L.append(row(res, k, lab, keys=('mIoU', 'seenIoU', 'novelIoU', 'hIoU', 'ECE'), extra=('drift',)))
    L += ['\\bottomrule', '\\end{tabular}']
    write(out, L)


