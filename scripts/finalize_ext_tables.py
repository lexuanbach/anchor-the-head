def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--in-dir', default='results/extended')
    ap.add_argument('--out-dir', default='tables')
    a = ap.parse_args()
    os.makedirs(a.out_dir, exist_ok=True)
    ap_ = os.path.join(a.in_dir, 'metrics_align.json')
    dp_ = os.path.join(a.in_dir, 'metrics_diag.json')
    if os.path.exists(ap_):
        res = json.load(open(ap_))['summary']
        tab_factorial(res, os.path.join(a.out_dir, 'tab_ext_factorial.tex'))
        tab_frontier(res, os.path.join(a.out_dir, 'tab_ext_frontier.tex'))
    else:
        print('SKIP: no metrics_align.json in', a.in_dir)
    if os.path.exists(dp_):
        tab_diag(json.load(open(dp_))['summary'], os.path.join(a.out_dir, 'tab_ext_diag.tex'))
    else:
        print('SKIP: no metrics_diag.json in', a.in_dir)
    for fn, gen, out in [('metrics_lposs.json', tab_lposs, 'tab_ext_lposs.tex'),
                         ('metrics_transfer.json', tab_transfer, 'tab_ext_transfer.tex'),
                         ('metrics_cost.json', tab_cost, 'tab_ext_cost.tex')]:
        fp = os.path.join(a.in_dir, fn)
        if os.path.exists(fp):
            d = json.load(open(fp))
            gen(d.get('summary', d), os.path.join(a.out_dir, out))
        else:
            print('SKIP: no', fn, 'in', a.in_dir)
    rp = os.path.join(a.in_dir, 'metrics_regime.json')
    if os.path.exists(rp):
        d = json.load(open(rp))['summary']
        if 'hIoU' in next(iter(d.values())):
            tab_regime(d, os.path.join(a.out_dir, 'tab_real_regime.tex'))
        else:
            print('SKIP tab_real_regime: no hIoU field yet')
    s3p = os.path.join(a.in_dir, 'metrics_stage3.json')
    s4p = os.path.join(a.in_dir, 'metrics_stage4.json')
    if os.path.exists(s3p):
        d3 = json.load(open(s3p))['summary']
        d4 = json.load(open(s4p))['summary'] if os.path.exists(s4p) else None
        if 'hIoU' in next(iter(d3.values())):
            tab_baselines(d3, d4, os.path.join(a.out_dir, 'tab_real_baselines.tex'))
        else:
            print('SKIP tab_real_baselines: no hIoU field yet')
    _apply_caption_overrides(a.out_dir)

