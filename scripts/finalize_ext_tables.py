"""Regenerate the extended-experiment tables from the metrics JSONs.

Reads (whichever are present):
  metrics_align.json  (scripts/pm_stage5_align.py)  -> tab_ext_factorial, tab_ext_frontier
  metrics_diag.json   (scripts/pm_stage7_diag.py)   -> tab_ext_diag
Pure file IO; no models. Run: python scripts/finalize_ext_tables.py --in-dir results/extended --out-dir tables
"""
from __future__ import annotations

import argparse
import json
import os

PRETTY = {
    'uncal': 'Uncalibrated (frozen baseline)',
    'globalT': 'Global temperature',
    'diffusion': 'Anchored graph diffusion',
    'laplacian': 'Generic graph Laplacian',
    'decoder_seen_only': 'Seen-only residual head',
    'B5_episodic': 'B5 pseudo-novel episodic training',
    'B6_learned_affinity': 'B6 learned class-agnostic affinity',
    'head_ce': 'Seen-only head (CE)',
    'C1_class_balanced': 'C1 class-balanced CE',
    'C2_focal': 'C2 focal loss',
    'C2_cosmargin': 'C2 cosine-margin loss',
    'C3_learned_scale': 'C3 learned logit scale',
    'C6_pure_only': 'C6 spatially pure patches only',
}


def m(res, k, f):
    return res[k][f]['mean']


def sd(res, k, f):
    return res[k][f]['std']


def cell(res, k, f, prec=1, with_std=True):
    v = m(res, k, f)
    if v != v:
        return '--'
    s = f'{v:.{prec}f}'
    if with_std and sd(res, k, f) == sd(res, k, f):
        s += f'\\std{{{sd(res, k, f):.1f}}}'
    return s


def row(res, k, label=None, keys=('mIoU', 'seenIoU', 'novelIoU', 'hIoU', 'ECE', 'ECE_novel'),
        extra=('drift', 'novel_rate')):
    lab = label or PRETTY.get(k, k.replace('_', ' '))
    vals = [cell(res, k, f) for f in keys] + [cell(res, k, f, with_std=False) for f in extra]
    ci = res[k].get('collapse_index')
    if ci is not None:
        vals.append(f'{ci:.2f}')
    return f'{lab} & ' + ' & '.join(vals) + ' \\\\'


def write(path, lines):
    with open(path, 'w') as fh:
        fh.write('\n'.join(lines) + '\n')
    print('wrote', path)


