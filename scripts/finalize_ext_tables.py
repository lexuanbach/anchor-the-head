def _apply_caption_overrides(out_dir):
    import re as _re, os as _os
    _dir = _os.path.dirname(_os.path.abspath(__file__))
    for _fname, _cap in _CAPTION_OVERRIDES.items():
        _p = _os.path.join(out_dir, _fname)
        _p = _os.path.normpath(_p)
        if not _os.path.exists(_p):
            continue
        _s = open(_p).read()
        _m = _re.search(r"\\caption\{", _s)
        if not _m:
            continue
        _i = _m.end(); _d = 1; _j = _i
        while _d and _j < len(_s):
            _d += (_s[_j] == "{") - (_s[_j] == "}"); _j += 1
        open(_p, "w").write(_s[:_m.start()] + "\\caption{" + _cap + "}" + _s[_j:])

