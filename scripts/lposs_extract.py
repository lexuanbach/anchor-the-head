"""Extract the LPOSS propagation functions VERBATIM from the authors' released repository.

For a direct numerical comparison against LPOSS under the same backbone and protocol, we do not re-derive the algorithm: we lift the authors' own implementation of
    normalize_connection_graph, get_lposs_laplacian, dfs_search, perform_lp
byte-for-byte out of segmentation/evaluation/lposs_eval.py and run it on our cached features.

Their module cannot be imported directly because its top-level imports pull in mmcv/mmseg
(`from mmseg.ops import resize`, `from mmseg.models import EncoderDecoder`), which serve the
EncoderDecoder wrappers further down the file and are unused by the four functions above.
mmcv-full==1.6.0 / mmsegmentation==0.27.0 also cannot be built against a modern torch, and the
authors' pinned pytorch 1.12.1/cu113 has no sm_90 kernels for an H100.

This script therefore performs a source-level extraction (via `ast`, so the function bodies are
copied exactly as written) and emits a standalone module that depends only on torch + faiss + cupy.
It prints a SHA-256 of each extracted function so the copy is auditable.

Run: python scripts/lposs_extract.py --lposs /path/to/LPOSS --out scripts/lposs_core_auto.py
"""
from __future__ import annotations

import argparse
import ast
import hashlib
import os

FUNCS = ["normalize_connection_graph", "get_lposs_laplacian", "dfs_search", "perform_lp"]

HEADER = '''"""AUTO-GENERATED by scripts/lposs_extract.py -- DO NOT EDIT.

Verbatim extraction of the LPOSS propagation from the authors' released code
(LPOSS/segmentation/evaluation/lposs_eval.py, Stojnic et al., CVPR 2025).
Only the imports below are ours; every function body is the authors' own, unmodified.
"""
import torch
import torch.nn.functional as F
import numpy as np

import cupy as cp
from cupyx.scipy.sparse import csr_matrix, diags, eye, coo_matrix
from cupyx.scipy.sparse import linalg as s_linalg

import faiss
import faiss.contrib.torch_utils  # noqa: F401  (registers torch tensor support)

'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lposs", required=True, help="path to the LPOSS checkout")
    ap.add_argument("--out", default="scripts/lposs_core_auto.py")
    a = ap.parse_args()

    src_path = os.path.join(a.lposs, "segmentation", "evaluation", "lposs_eval.py")
    src = open(src_path).read()
    tree = ast.parse(src)
    lines = src.splitlines(keepends=True)

    chunks, found = [], {}
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name in FUNCS:
            start = node.lineno - 1
            end = node.end_lineno
            body = "".join(lines[start:end])
            found[node.name] = hashlib.sha256(body.encode()).hexdigest()[:16]
            chunks.append((FUNCS.index(node.name), body))

    missing = [f for f in FUNCS if f not in found]
    if missing:
        raise SystemExit(f"ERROR: functions not found in {src_path}: {missing}")

    chunks.sort()
    out = HEADER + "\n\n".join(body.rstrip() for _, body in chunks) + "\n"
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    with open(a.out, "w") as fh:
        fh.write(out)

    print(f"extracted {len(found)} functions from {src_path} -> {a.out}")
    for f in FUNCS:
        print(f"  {f:28s} sha256[:16]={found[f]}")
    print(f"  {'FULL MODULE':28s} sha256[:16]={hashlib.sha256(out.encode()).hexdigest()[:16]}")


if __name__ == "__main__":
    main()
